logger = logging.getLogger(__name__)


# ==========================================
# DATABASE CONNECTION
# ==========================================

def get_connection():
    """Connect to PostgreSQL."""

    database_url = (
        os.getenv("DATABASE_URL")
        or os.getenv("POSTGRES_URL")
        or os.getenv("POSTGRES_PRISMA_URL")
    )

    if not database_url or not database_url.strip():
        raise RuntimeError(
            "DATABASE_URL is missing. Configure your PostgreSQL URL "
            "in .env or deployment environment variables."
        )

    database_url = database_url.strip()

    if database_url.startswith("postgres://"):
        database_url = "postgresql://" + database_url[len("postgres://"):]

    return psycopg2.connect(
        database_url,
        cursor_factory=RealDictCursor,
        connect_timeout=15,
        sslmode="require",
    )


# ==========================================
# CREATE HISTORY AND FEEDBACK TABLES
# ==========================================

def create_history_table():
    """Initialize prediction history and feedback tables."""

    database_url = (
        os.getenv("DATABASE_URL")
        or os.getenv("POSTGRES_URL")
        or os.getenv("POSTGRES_PRISMA_URL")
    )

    if not database_url:
        logger.warning("Database URL missing; tables not initialized.")
        return False

    connection = None

    try:
        connection = get_connection()

        with connection.cursor() as cursor:
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS prediction_history (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    song TEXT NOT NULL,
                    mood TEXT NOT NULL,
                    confidence DOUBLE PRECISION NOT NULL DEFAULT 0,
                    intensity TEXT NOT NULL DEFAULT 'Low',
                    date TEXT NOT NULL
                )
            """)

            cursor.execute("""
                CREATE TABLE IF NOT EXISTS user_feedback (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    song_name TEXT NOT NULL DEFAULT '',
                    mood TEXT NOT NULL DEFAULT '',
                    confidence DOUBLE PRECISION NOT NULL DEFAULT 0,
                    helpfulness TEXT NOT NULL DEFAULT '',
                    rating INTEGER CHECK (
                        rating IS NULL OR rating BETWEEN 1 AND 5
                    ),
                    feedback TEXT NOT NULL DEFAULT '',
                    submitted_at TEXT NOT NULL DEFAULT ''
                )
            """)

        connection.commit()
        logger.info("PostgreSQL history and feedback tables are ready.")
        return True

    except Exception:
        if connection:
            connection.rollback()
        logger.exception("Failed to initialize history/feedback tables.")
        raise

    finally:
        if connection:
            connection.close()


