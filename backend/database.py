# ==========================================
# SAVE PREDICTION
# ==========================================

def save_prediction(song, mood, confidence, intensity, date):
    """Save a mood prediction."""

    connection = None

    try:
        connection = get_connection()

        with connection.cursor() as cursor:
            cursor.execute("""
                INSERT INTO prediction_history
                    (song, mood, confidence, intensity, date)
                VALUES (%s, %s, %s, %s, %s)
                RETURNING id
            """, (
                str(song),
                str(mood),
                float(confidence),
                str(intensity),
                str(date),
            ))

            result = cursor.fetchone()

        connection.commit()
        return dict(result) if result else None

    except Exception:
        if connection:
            connection.rollback()
        logger.exception("Failed to save prediction.")
        raise

    finally:
        if connection:
            connection.close()


# ==========================================
# GET PREDICTION HISTORY
# ==========================================

def get_predictions():
    """Return all predictions, newest first."""

    connection = None

    try:
        connection = get_connection()

        with connection.cursor() as cursor:
            cursor.execute("""
                SELECT id, song, mood, confidence, intensity, date
                FROM prediction_history
                ORDER BY id DESC
            """)

            rows = cursor.fetchall()

        return [dict(row) for row in rows]

    except Exception:
        logger.exception("Failed to fetch prediction history.")
        raise

    finally:
        if connection:
            connection.close()


