# ==========================================
# SAVE USER FEEDBACK
# ==========================================

def save_feedback(feedback_data):
    """Save feedback supplied by the Flask feedback route."""

    if not isinstance(feedback_data, dict):
        raise ValueError("Feedback must be provided as a dictionary.")

    song_name = str(
        feedback_data.get("songName")
        or feedback_data.get("song_name")
        or ""
    ).strip()

    mood = str(feedback_data.get("mood") or "").strip()
    helpfulness = str(feedback_data.get("helpfulness") or "").strip()
    feedback = str(feedback_data.get("feedback") or "").strip()

    submitted_at = str(
        feedback_data.get("submittedAt")
        or feedback_data.get("submitted_at")
        or ""
    ).strip()

    try:
        confidence = float(feedback_data.get("confidence") or 0)
    except (TypeError, ValueError):
        raise ValueError("Confidence must be a valid number.")

    rating_value = feedback_data.get("rating")
    rating = None

    if rating_value not in (None, ""):
        try:
            rating = int(rating_value)
        except (TypeError, ValueError):
            raise ValueError("Rating must be an integer from 1 to 5.")

        if not 1 <= rating <= 5:
            raise ValueError("Rating must be between 1 and 5.")

    connection = None

    try:
        connection = get_connection()

        with connection.cursor() as cursor:
            cursor.execute("""
                INSERT INTO user_feedback (
                    song_name,
                    mood,
                    confidence,
                    helpfulness,
                    rating,
                    feedback,
                    submitted_at
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s)
                RETURNING id
            """, (
                song_name,
                mood,
                confidence,
                helpfulness,
                rating,
                feedback,
                submitted_at,
            ))

            result = cursor.fetchone()

        connection.commit()
        return dict(result) if result else None

    except Exception:
        if connection:
            connection.rollback()
        logger.exception("Failed to save user feedback.")
        raise

    finally:
        if connection:
            connection.close()


# ==========================================
# REGISTER USER
# ==========================================

def register_user(name, email, password):
    """Register a user with a securely hashed password."""

    name = name.strip()
    email = email.strip().lower()

    if not name or not email or not password:
        raise ValueError("Name, email and password are required.")

    if len(password) < 8:
        raise ValueError("Password must contain at least 8 characters.")

    if len(name) > 150 or len(email) > 255:
        raise ValueError("Name or email is too long.")

    password_hash = generate_password_hash(password)
    connection = None

    try:
        connection = get_connection()

        with connection.cursor() as cursor:
            cursor.execute("""
                INSERT INTO app_users (name, email, password_hash)
                VALUES (%s, %s, %s)
                RETURNING id, name, email
            """, (name, email, password_hash))

            user = cursor.fetchone()

        connection.commit()
        logger.info("User registered successfully.")
        return dict(user) if user else None

    except UniqueViolation:
        if connection:
            connection.rollback()
        raise ValueError("This email is already registered.")

    except Exception:
        if connection:
            connection.rollback()
        logger.exception("User registration failed.")
        raise

    finally:
        if connection:
            connection.close()


# ==========================================
# AUTHENTICATE USER
# ==========================================

def authenticate_user(email, password):
    """Verify login credentials without returning the password hash."""

    email = email.strip().lower()
    connection = None

    try:
        connection = get_connection()

        with connection.cursor() as cursor:
            cursor.execute("""
                SELECT id, name, email, password_hash
                FROM app_users
                WHERE email = %s
                LIMIT 1
            """, (email,))

            user = cursor.fetchone()

        if not user:
            return None

        if not check_password_hash(user["password_hash"], password):
            return None

        return {
            "id": user["id"],
            "name": user["name"],
            "email": user["email"],
        }

    except Exception:
        logger.exception("User authentication failed.")
        raise

    finally:
        if connection:
            connection.close()
